/** The sample tree before or after the remediator's fix for ARC-001 lands. */
export function sampleFs(fixed: boolean): WorkspaceFs {
  const keep = fixed ? "add" : "del";
  const files: Record<string, string> = {
    ...STATIC_FILES,
    [EXPORT.path]: at(firstLine(EXPORT), EXPORT_HEAD, side(EXPORT, keep)),
    [SESSION.path]: at(firstLine(SESSION), SESSION_HEAD, side(SESSION, keep)),
  };
  if (fixed) {
    for (const f of FLAGSHIP.remediation.files) if (f.status === "A") files[f.path] = [...side(f, "add"), ""].join("\n");
  }
  return memoryFs(files);
}
