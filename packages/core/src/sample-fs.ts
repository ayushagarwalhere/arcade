/** Places `body` so its first line is `startLine`, whatever the header's length. */
function at(startLine: number, head: string[], body: string[]): string {
  const lead = head.slice(0, startLine - 1);
  while (lead.length < startLine - 1) lead.push("");
  return [...lead, ...body, ""].join("\n");
}

